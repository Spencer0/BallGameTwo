"""Contact sheet + icon atlas from build/thumbs and build/catalog.

python3 tools/sheet.py [--out build/sheet.png] [--ids a,b] [--cell 160]
Writes:
  build/sheet.png          labelled contact sheet (review)
  assets/icons.png         96px icon atlas (game), assets/icons.json index
  ASSETS.md                asset table
"""
import glob, json, os, sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
args = sys.argv[1:]
def opt(name, default=None):
    return args[args.index(name) + 1] if name in args else default

cats = []
for p in sorted(glob.glob(os.path.join(ROOT, 'build', 'catalog', 'L*.json'))):
    cats += json.load(open(p))
ids = opt('--ids')
only = ids.split(',') if ids else None
lv = opt('--levels')
if lv:
    lvls = {int(x) for x in lv.split(',')}
    only = [c['id'] for c in cats if c['level'] in lvls]
thumbs = {os.path.basename(p)[:-4]: p for p in glob.glob(os.path.join(ROOT, 'build', 'thumbs', '*.png'))}
order = [c['id'] for c in cats if c['id'] in thumbs]
if only:
    order = [i for i in only if i in thumbs]
elif not order:
    order = sorted(thumbs)
meta = {c['id']: c for c in cats}

cell = int(opt('--cell', 160))
cols = int(opt('--cols', 8))
rows = (len(order) + cols - 1) // cols
sheet = Image.new('RGB', (cols * cell, rows * (cell + 28)), (255, 246, 230))
draw = ImageDraw.Draw(sheet)
try:
    font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 12)
except Exception:
    font = ImageFont.load_default()
for i, aid in enumerate(order):
    x, y = (i % cols) * cell, (i // cols) * (cell + 28)
    im = Image.open(thumbs[aid]).convert('RGBA').resize((cell, cell), Image.LANCZOS)
    bg = Image.new('RGBA', im.size, (255, 246, 230, 255) if (i + i // cols) % 2 == 0 else (250, 236, 214, 255))
    sheet.paste(Image.alpha_composite(bg, im).convert('RGB'), (x, y))
    m = meta.get(aid, {})
    label = aid if not m else f"{aid} {m['tris'][0]}t"
    draw.text((x + 4, y + cell + 2), label[:22], fill=(42, 30, 63), font=font)
    if m:
        sz = m['size']
        draw.text((x + 4, y + cell + 15), f"{sz*100:.1f}cm" if sz < 1 else f"{sz:.1f}m", fill=(120, 100, 150), font=font)
out = opt('--out', os.path.join(ROOT, 'docs', 'contact_sheet.png'))
os.makedirs(os.path.dirname(out), exist_ok=True)
sheet.save(out)
print('sheet', out, len(order))

if not only:
    # icon atlas for the game
    icon = 96
    acols = 16
    arows = (len(order) + acols - 1) // acols
    atlas = Image.new('RGBA', (acols * icon, max(1, arows) * icon), (0, 0, 0, 0))
    index = {}
    for i, aid in enumerate(order):
        im = Image.open(thumbs[aid]).convert('RGBA').resize((icon, icon), Image.LANCZOS)
        atlas.paste(im, ((i % acols) * icon, (i // acols) * icon))
        index[aid] = i
    os.makedirs(os.path.join(ROOT, 'assets'), exist_ok=True)
    atlas.save(os.path.join(ROOT, 'assets', 'icons.png'), optimize=True)
    json.dump({'cell': icon, 'cols': acols, 'rows': arows, 'index': index}, open(os.path.join(ROOT, 'assets', 'icons.json'), 'w'))
    # ASSETS.md
    lines = ['# Asset contact sheet', '', 'Generated by `tools/sheet.py` from the Blender build (`tools/blender/build.py`).',
             'Every asset is a Python function in `tools/blender/assets/`; thumbnails are EEVEE toon + Freestyle renders.',
             'Characters (Lint rig parts, Madame Prudence) are built by `tools/blender/chars.py`.', '',
             '![contact sheet](docs/contact_sheet.png)', '',
             f'**{len(order)} object types.**', '',
             '| id | name | level | size | tris LOD0/LOD1 | material | collider | variants |', '|---|---|---|---|---|---|---|---|']
    for aid in order:
        m = meta.get(aid)
        if not m: continue
        sz = m['size']
        lines.append(f"| `{aid}` | {m['name']} | {m['level']} | {sz*100:.1f} cm |" if sz < 1 else f"| `{aid}` | {m['name']} | {m['level']} | {sz:.1f} m |")
        lines[-1] += f" {m['tris'][0]}/{m['tris'][1]} | {m['mat']} | {m['collider']['kind']} | {', '.join(m['variants']) or '-'} |"
    open(os.path.join(ROOT, 'ASSETS.md'), 'w').write('\n'.join(lines) + '\n')
    print('atlas + ASSETS.md written')

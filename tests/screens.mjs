// Tour every screen at an iPhone viewport and screenshot it.  node tests/screens.mjs [viewport] [outdir]
import fs from 'node:fs';
import { serve, launch, drag } from './harness.mjs';
const vp = process.argv[2] || 'iphone14';
const out = process.argv[3] || 'build/screens';
fs.mkdirSync(out, { recursive: true });
const { srv, url } = await serve();
const { browser, page, errors } = await launch(vp);
const shot = async (name) => { await page.waitForTimeout(450); await page.screenshot({ path: `${out}/${vp}_${name}.png` }); console.log('shot', name); };
await page.goto(url);
await page.waitForSelector('.title-screen.in', { timeout: 60000 });
await shot('01_title');
await page.tap('[data-act=settings]');
await shot('02_settings');
await page.tap('[data-act=close-settings]');
await page.tap('[data-act=collection]');
await shot('03_collection');
await page.tap('[data-act=tab][data-tab=skins]');
await shot('04_skins');
await page.tap('[data-act=back-from-collection]');
await page.tap('[data-act=play]');
await shot('05_levels');
await page.tap('[data-act=level][data-i="0"]');
await shot('06_mode');
await page.tap('[data-act=start][data-mode=timed]');
await page.waitForSelector('.dialog.in', { timeout: 10000 });
await page.waitForTimeout(1500);
await shot('07_dialog');
await page.tap('.dialog .skip');
await page.waitForFunction(() => window.__game.session && document.body.classList.contains('playing'), null, { timeout: 60000 });
await page.waitForTimeout(800);
await shot('08_hud');
await drag(page, 200, 650, 10, -70, 2500);
await shot('09_rolling');
await page.tap('#hud-pause');
await shot('10_pause');
await page.tap('[data-act=finish]');
await page.waitForSelector('.results-screen.in', { timeout: 10000 });
await page.waitForTimeout(2500);
await shot('11_results');
await page.tap('[data-act=postcard]');
await page.waitForSelector('.postcard-img', { timeout: 15000 });
await shot('12_postcard');
console.log('errors:', errors.length ? '\n' + errors.join('\n') : 'none');
await browser.close();
srv.close();
